import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";

const contractUrl = new URL("../contracts/learning-event.schema.json", import.meta.url);
const outputUrl = new URL(
  "../src/generated/validateLearningEvent.ts",
  import.meta.url,
);
mkdirSync(new URL("../src/generated/", import.meta.url), { recursive: true });
const source = readFileSync(contractUrl, "utf8");
const schema = JSON.parse(source);
const fingerprint = createHash("sha256").update(source).digest("hex");

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  code: { source: true, esm: true, optimize: true },
});
addFormats(ajv);
const validate = ajv.compile(schema);
const standalone = standaloneCode(ajv, validate);
const generated = standalone
  .replace(
    'const func1 = require("ajv/dist/runtime/ucs2length").default;',
    [
      "const func1 = (value) => {",
      "  let length = 0;",
      "  for (const _character of value) length += 1;",
      "  return length;",
      "};",
    ].join("\n"),
  )
  .replace(
    'const formats0 = require("ajv-formats/dist/formats").fullFormats["date-time"];',
    'const formats0 = fullFormats["date-time"];',
  );
if (generated.includes("require(")) {
  throw new Error("Generated validator contains an unresolved CommonJS import.");
}

writeFileSync(
  outputUrl,
  [
    "// @ts-nocheck",
    "// Generated by scripts/generate-learning-event-validator.mjs.",
    `// Contract SHA-256: ${fingerprint}`,
    'import { fullFormats } from "ajv-formats/dist/formats.js";',
    generated,
    "",
  ].join("\n"),
);

console.log(`Generated ${fileURLToPath(outputUrl)} from ${fileURLToPath(contractUrl)}.`);
